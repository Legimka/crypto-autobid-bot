# Рынки для проверки стаканов P2P CryptoBot: python check_app.py <сессия>
# Здесь же — настройки перебивки P2P (модуль autobid/cryptobot/p2p.py). Поля рынка:
#   enabled       — False, чтобы временно выключить рынок (по умолчанию включён)
#   session       — сессия аккаунта (наблюдатель и перебивающий, если не заданы отдельно)
#   observer      — чей аккаунт читает стакан (по умолчанию = session)
#   trader        — чей аккаунт меняет курс (по умолчанию = session)
#   side          — "buy" (вкладка «Купить») или "sell" (вкладка «Продать»)
#   floating      — True, если объявление с плавающей ценой (процент от биржевого курса)
#   step          — шаг цены (например "0.01"); пусто → 0.0001 для курса < 10, иначе 0.01
#   initial       — исходный курс (для коридора); max_dev_pct — макс. отклонение от него, %
#   on_limit      — что делать у края коридора (ответ заказчика, п.3): "reset" (вернуться к initial
#                   и сделать паузу — основной режим), "hold" (встать на границу и держать место),
#                   "pause" (не менять курс, временно приостановить). По умолчанию "reset".
#   limit_pause_sec — длительность паузы для reset/pause (по умолчанию 30 с)
#   min_price / max_price — абсолютные пределы курса (ТЗ §4): бот не выходит за них никогда
#   max_jump      — не менять курс сильнее, чем на столько % за одну правку (защита от аномалий)
#   max_changes   — предел числа перебиваний одного объявления (ТЗ §4); пусто → без предела
#   stability_polls — учитывать конкурента, только если его курс держится N опросов (ТЗ §7,
#                   защита от «дёрганья»; 2 по умолчанию, 1 — выключить)
#   difference    — не перебивать, если отрыв от конкурента меньше (чтобы не дёргать по мелочи)
#   cooldown_changes / cooldown_min — не больше N правок одного объявления, потом пауза M минут
#   poll_sec      — как часто перечитывать стакан (6 с по умолчанию)
#   trader_mode   — "app" (менять курс через API мини-приложения, быстро) или "chat" (диалог в чате)
